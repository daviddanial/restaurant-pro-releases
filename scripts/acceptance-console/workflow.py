#!/usr/bin/env python3
"""Automated clinical workflow check (P2): assign → claim → report → sign → deliver.

Why this exists
---------------
Stages 1 and 2 prove a study *arrives* in TeleRad and is ready to read. They stop
exactly where the manual operator used to start: Dispatch → Worklist → report →
sign → hospital portal. A study that "reaches dispatch" is not a finished
radiology report, so this module closes the loop through TeleRad's own REST API
and ends on the hospital being able to download the signed PDF.

What it does, keyed to the study the caller names (the fixture's
StudyInstanceUID, resolved against the hospital's study list):

  1. ``wf-assign``     hospital assigns the study to the radiologist (dispatch)
  2. ``wf-claim``      the radiologist claims it (worklist)
  3. ``wf-report``     the radiologist saves a synthetic draft report
  4. ``wf-sign``       the radiologist signs it (PDF rendered + stored)
  5. ``wf-delivered``  the hospital sees status DELIVERED and the report listed
  6. ``wf-pdf``        the hospital downloads the PDF (``%PDF-`` magic, size > 0)

The report text is deliberately synthetic and says so; this module must never be
mistaken for a clinical record.

This is a pure module: no FastAPI imports, so the console and the standalone
probe can both import it. It never logs a password or a token.

Honesty note (learned from the live API, not assumed): the study detail JSON
(``{study, series, report}``) does **not** expose ``claimedAt`` — the field
exists on the entity but is absent from every response DTO. ``wf-claim``
therefore verifies the observable claim transition (the claim call returns 200
and the study is ``IN_PROGRESS`` assigned to the radiologist) and says so in the
detail, rather than inventing a field the API never returns.
"""
from __future__ import annotations

import json
import time
from pathlib import Path

import httpx

STAGE = 3
DEFAULT_TIMEOUT = 20.0

FINDINGS = "Automated acceptance-test exam — synthetic report generated by the console."
IMPRESSION = "Acceptance test — no clinical interpretation. Workflow verification only."

_LABELS: list[tuple[str, str]] = [
    ("wf-assign", "Study assigned to the radiologist (dispatch)"),
    ("wf-claim", "Radiologist claimed the study (worklist)"),
    ("wf-report", "Draft report saved"),
    ("wf-sign", "Report signed"),
    ("wf-delivered", "Report delivered back to the hospital"),
    ("wf-pdf", "Hospital can download the signed PDF"),
]

# The most recent run's resolved ids — the console may read this after calling
# run_workflow(). ``run_workflow_detailed`` returns it directly, without the
# module-level indirection, and is preferred by callers that can use it.
LAST_RESULT: dict = {}


# ----------------------------------------------------------------------- helpers
def _short(value) -> str:
    text = str(value or "")
    return text if len(text) <= 8 else text[:8] + "…"


def _redact(text: str, secrets: list[str]) -> str:
    """Never let a password or token reach a check detail."""
    out = str(text)
    for secret in secrets:
        if secret:
            out = out.replace(str(secret), "<redacted>")
    return out[:300]


def _creds_pair(creds):
    """Accept ``{"email","password"}`` (or a 2-tuple) and return the pair."""
    if not creds:
        return None, None
    if isinstance(creds, dict):
        email = creds.get("email") or creds.get("username") or creds.get("user")
        password = creds.get("password") or creds.get("pass")
    elif isinstance(creds, (tuple, list)) and len(creds) >= 2:
        email, password = creds[0], creds[1]
    else:
        return None, None
    return (email, password) if email and password else (None, None)


def _login(api_base: str, creds) -> dict:
    email, password = _creds_pair(creds)
    if not email or not password:
        raise ValueError("no credentials configured")
    with httpx.Client(timeout=DEFAULT_TIMEOUT) as client:
        resp = client.post(f"{api_base.rstrip('/')}/api/auth/login",
                           json={"email": email, "password": password})
    if resp.status_code != 200:
        raise RuntimeError(f"login rejected with HTTP {resp.status_code}")
    data = resp.json()
    if not data.get("accessToken"):
        raise RuntimeError("login response carried no access token")
    return data


class _Api:
    """A logged-in session: one token, one base URL, never leaked."""

    def __init__(self, api_base: str, login: dict):
        self.base = api_base.rstrip("/")
        self.user = login
        self.token = login["accessToken"]
        self.client = httpx.Client(timeout=DEFAULT_TIMEOUT)

    def close(self) -> None:
        self.client.close()

    def _headers(self) -> dict:
        return {"Authorization": f"Bearer {self.token}"}

    def get(self, path: str, **kw) -> httpx.Response:
        return self.client.get(f"{self.base}{path}", headers=self._headers(), **kw)

    def post(self, path: str, json=None, **kw) -> httpx.Response:
        return self.client.post(f"{self.base}{path}", headers=self._headers(), json=json, **kw)

    def put(self, path: str, json=None, **kw) -> httpx.Response:
        return self.client.put(f"{self.base}{path}", headers=self._headers(), json=json, **kw)


def _login_actor(api_base: str, primary, admin, secrets: list[str]) -> tuple[_Api, bool, str | None]:
    """Log in the primary account; fall back to ADMIN only when configured.

    Returns ``(api, used_fallback, reason)``. ``reason`` is the sanitized reason
    the primary account could not be used.
    """
    try:
        return _Api(api_base, _login(api_base, primary)), False, None
    except Exception as exc:  # bad password, locked account, API down
        if not admin:
            raise
        return _Api(api_base, _login(api_base, admin)), True, _redact(
            f"{type(exc).__name__}: {exc}", secrets)


def _check(cid: str, label: str, status: str, detail: str, plain: str) -> dict:
    return {"id": cid, "stage": STAGE, "label": label, "status": status,
            "detail": detail, "plain": plain}


def _find_study(rows, key) -> dict | None:
    key = str(key)
    for row in rows:
        if str(row.get("studyInstanceUid")) == key:
            return row
    for row in rows:  # tolerate being handed the internal study UUID instead
        if str(row.get("id")) == key:
            return row
    return None


def _study_detail(api: _Api, study_id: str) -> dict:
    resp = api.get(f"/api/studies/{study_id}")
    if resp.status_code != 200:
        raise RuntimeError(f"study detail HTTP {resp.status_code}")
    return (resp.json() or {}).get("study") or {}


def _fail_all(reason: str) -> list[dict]:
    return [
        _check(cid, label, "fail", f"could not run: {reason}",
               "The clinical workflow could not run, so this step is not a pass.")
        for cid, label in _LABELS
    ]


def _pdf_check(hospital: "_Api", report_id: str, out_dir: Path,
               secrets: list[str]) -> tuple[dict, str | None]:
    """Download the delivered PDF, save it, and build the ``wf-pdf`` check.

    Returns ``(check, pdf_path)``. A download that succeeds but cannot be written
    to ``out_dir`` still passes (the hospital *can* download it) and says why the
    file is not on disk — an evidence-storage problem is not a product failure.
    """
    label = _LABELS[5][1]
    try:
        resp = hospital.get(f"/api/reports/{report_id}/pdf")
        magic_ok = resp.content[:5] == b"%PDF-"
        size = len(resp.content)
        ok = resp.status_code == 200 and magic_ok and size > 0
        filename = f"delivered-{report_id}.pdf"
        pdf_path = None
        saved_note = ""
        if ok:
            try:
                out_dir.mkdir(parents=True, exist_ok=True)
                path = out_dir / filename
                path.write_bytes(resp.content)
                pdf_path = str(path)
            except Exception as exc:  # evidence-file problem, not a download failure
                saved_note = f" · could not save the file: {_redact(str(exc), secrets)}"
        if not ok:
            return _check("wf-pdf", label, "fail",
                          f"HTTP {resp.status_code} · {size} bytes · "
                          f"%PDF- magic {'ok' if magic_ok else 'MISSING'}",
                          "The hospital could not download the signed report as a PDF."), None
        link = (f' · <a href="/api/reports/{filename}">{filename}</a>'
                if pdf_path else saved_note)
        return _check("wf-pdf", label, "pass",
                      f"HTTP 200 · {size} bytes · %PDF- magic ok · saved {filename}{link}",
                      "The hospital can download the signed report as a PDF."), pdf_path
    except Exception as exc:
        return _check("wf-pdf", label, "fail",
                      _redact(f"{type(exc).__name__}: {exc}", secrets),
                      "The hospital-side PDF download failed."), None


def save_delivered_pdf(api_base: str, report_id: str, hospital_creds, out_dir,
                       admin_creds=None) -> tuple[dict, str | None]:
    """Non-mutating helper: fetch a signed report's PDF as the hospital would.

    Used by the smoke to prove the save + ``/api/reports/`` link without touching
    the workflow state again. Returns ``(wf-pdf check, saved path or None)``.
    """
    secrets: list[str] = []
    for creds in (hospital_creds, admin_creds):
        _, password = _creds_pair(creds)
        if password:
            secrets.append(password)
    hospital, _, _ = _login_actor(api_base, hospital_creds, admin_creds, secrets)
    try:
        return _pdf_check(hospital, report_id, Path(out_dir), secrets)
    finally:
        hospital.close()


# ------------------------------------------------------------------------- run
def run_workflow_detailed(
    api_base: str,
    study_id: str,
    hospital_id: str,
    radiologist_creds,
    hospital_creds,
    out_dir,
    admin_creds=None,
) -> tuple[list[dict], dict]:
    """Run the clinical workflow. Returns ``(checks, result)``.

    ``study_id`` is the fixture's **StudyInstanceUID**; it is resolved against
    ``/api/hospitals/{hospital_id}/studies``. If the study is not in that list
    the workflow returns no checks at all — stage 2 has already reported the
    miss and there is nothing to automate.

    ``result`` carries ``{study_id, study_uid, report_id, pdf_path}`` for the
    caller (internal study UUID, the UID used to find it, the signed report id,
    and the saved PDF path).
    """
    global LAST_RESULT
    out_dir = Path(out_dir)
    secrets: list[str] = []
    for creds in (radiologist_creds, hospital_creds, admin_creds):
        _, password = _creds_pair(creds)
        if password:
            secrets.append(password)

    result: dict = {
        "study_id": None,
        "study_uid": str(study_id) if study_id else None,
        "report_id": None,
        "pdf_path": None,
    }
    LAST_RESULT = result
    checks: list[dict] = []
    started = time.monotonic()

    # --- resolve the study from the hospital's own list ----------------------
    try:
        hospital, _, _ = _login_actor(api_base, hospital_creds, admin_creds, secrets)
    except Exception as exc:
        checks = _fail_all(_redact(f"{type(exc).__name__}: {exc}", secrets))
        return checks, result

    try:
        listed = hospital.get(f"/api/hospitals/{hospital_id}/studies")
        if listed.status_code != 200:
            hospital.close()
            checks = _fail_all(f"hospital study list HTTP {listed.status_code}")
            return checks, result
        row = _find_study(listed.json(), study_id)
        if row is None:
            # Not our study — stage 2 already reported the miss. Nothing to do.
            hospital.close()
            return [], result
    except Exception as exc:
        hospital.close()
        checks = _fail_all(_redact(f"{type(exc).__name__}: {exc}", secrets))
        return checks, result

    internal_id = str(row.get("id"))
    study_uid = str(row.get("studyInstanceUid"))
    result["study_id"] = internal_id

    # --- clinical actor: the radiologist; ADMIN only as a fallback -----------
    try:
        clinical, clinical_fallback, clinical_reason = _login_actor(
            api_base, radiologist_creds, admin_creds, secrets)
    except Exception as exc:
        hospital.close()
        checks = _fail_all(_redact(f"radiologist login failed: {type(exc).__name__}: {exc}",
                                   secrets))
        return checks, result

    actor_name = clinical.user.get("fullName") or "the radiologist"
    actor_id = str(clinical.user.get("userId") or "")
    blocked: str | None = None

    def add(cid: str, label: str, status: str, detail: str, plain: str) -> None:
        checks.append(_check(cid, label, status, detail, plain))

    def skip(cid: str, label: str) -> None:
        add(cid, label, "fail",
            f"could not run: the earlier step “{blocked}” did not succeed",
            "This step could not run because a required earlier step failed.")

    try:
        # ---- 1. assign (dispatch) ------------------------------------------
        # Dispatch is the HOSPITAL user's action, not the radiologist's — the
        # radiologist only claims/reports/signs below.
        if not actor_id:
            raise RuntimeError("login returned no user id to assign to")
        resp = hospital.post(f"/api/studies/{internal_id}/assign",
                             json={"radiologistId": actor_id})
        if resp.status_code not in (200, 201):
            raise RuntimeError(f"assign HTTP {resp.status_code}")
        study = _study_detail(clinical, internal_id)
        assigned = str(study.get("assignedTo") or "")
        ok = study.get("status") == "IN_PROGRESS" and assigned == actor_id
        detail = (f"assignedTo={actor_name} ({_short(actor_id)}), status={study.get('status')}"
                  + (" (ADMIN fallback login)" if clinical_fallback else ""))
        if not ok:
            blocked = "assign"
            add("wf-assign", _LABELS[0][1], "fail",
                f"expected status=IN_PROGRESS assignedTo={_short(actor_id)}, got "
                f"status={study.get('status')} assignedTo={_short(assigned)}",
                "The study was not assigned to the radiologist.")
        else:
            add("wf-assign", _LABELS[0][1], "pass", detail,
                f"The study was assigned to {actor_name} (dispatch).")
    except Exception as exc:
        blocked = "assign"
        add("wf-assign", _LABELS[0][1], "fail",
            _redact(f"{type(exc).__name__}: {exc}", secrets),
            "The dispatch step failed, so the study was not assigned.")

    # ---- 2. claim (worklist) ------------------------------------------------
    if blocked:
        skip("wf-claim", _LABELS[1][1])
    else:
        try:
            resp = clinical.post(f"/api/studies/{internal_id}/claim")
            if resp.status_code != 200:
                raise RuntimeError(f"claim HTTP {resp.status_code}")
            study = _study_detail(clinical, internal_id)
            assigned = str(study.get("assignedTo") or "")
            ok = study.get("status") == "IN_PROGRESS" and assigned == actor_id
            detail = (f"claim HTTP 200 · status={study.get('status')} · "
                      f"assignedTo={_short(assigned)} · claimedAt is recorded by the backend "
                      f"but not exposed by any API response")
            if not ok:
                blocked = "claim"
                add("wf-claim", _LABELS[1][1], "fail",
                    f"expected IN_PROGRESS assigned to {_short(actor_id)}, got "
                    f"status={study.get('status')} assignedTo={_short(assigned)}",
                    "The radiologist did not end up owning the study.")
            else:
                add("wf-claim", _LABELS[1][1], "pass", detail,
                    "The radiologist claimed the study (worklist).")
        except Exception as exc:
            blocked = "claim"
            add("wf-claim", _LABELS[1][1], "fail",
                _redact(f"{type(exc).__name__}: {exc}", secrets),
                "The worklist claim failed.")

    # ---- 3. save the synthetic draft report ---------------------------------
    report_id = None
    if blocked:
        skip("wf-report", _LABELS[2][1])
    else:
        try:
            resp = clinical.put(f"/api/studies/{internal_id}/report",
                                json={"findings": FINDINGS, "impression": IMPRESSION,
                                      "critical": False})
            if resp.status_code != 200:
                raise RuntimeError(f"save report HTTP {resp.status_code}")
            dto = resp.json() or {}
            report_id = dto.get("id")
            ok = bool(report_id) and dto.get("status") == "DRAFT"
            detail = (f"report {_short(report_id)} saved · status={dto.get('status')} · "
                      f"findings + impression stored, critical=false")
            if not ok:
                blocked = "report"
                add("wf-report", _LABELS[2][1], "fail",
                    f"expected a report id with status=DRAFT, got id={_short(report_id)} "
                    f"status={dto.get('status')}",
                    "The draft report was not saved.")
            else:
                result["report_id"] = str(report_id)
                add("wf-report", _LABELS[2][1], "pass", detail,
                    "The radiologist started the report.")
        except Exception as exc:
            blocked = "report"
            add("wf-report", _LABELS[2][1], "fail",
                _redact(f"{type(exc).__name__}: {exc}", secrets),
                "The draft report could not be saved.")

    # ---- 4. sign (PDF rendered + stored) ------------------------------------
    if blocked:
        skip("wf-sign", _LABELS[3][1])
    else:
        try:
            resp = clinical.post(f"/api/studies/{internal_id}/report/sign")
            if resp.status_code != 200:
                raise RuntimeError(f"sign HTTP {resp.status_code}")
            dto = resp.json() or {}
            ok = (dto.get("status") == "SIGNED" and dto.get("hasPdf") is True
                  and bool(dto.get("signedAt")))
            detail = (f"status={dto.get('status')} · hasPdf={dto.get('hasPdf')} · "
                      f"signedAt={dto.get('signedAt')}")
            if not ok:
                blocked = "sign"
                add("wf-sign", _LABELS[3][1], "fail", detail,
                    "The report did not reach the signed state with a stored PDF.")
            else:
                add("wf-sign", _LABELS[3][1], "pass", detail,
                    "The report was signed.")
        except Exception as exc:
            blocked = "sign"
            add("wf-sign", _LABELS[3][1], "fail",
                _redact(f"{type(exc).__name__}: {exc}", secrets),
                "The report could not be signed.")

    # ---- 5. delivered back to the hospital ----------------------------------
    if blocked or not result["report_id"]:
        skip("wf-delivered", _LABELS[4][1])
    else:
        try:
            listed = hospital.get(f"/api/hospitals/{hospital_id}/studies")
            rows = listed.json() if listed.status_code == 200 else []
            delivered = _find_study(rows, study_uid) or {}
            rep_resp = hospital.get(f"/api/hospitals/{hospital_id}/reports")
            reports = rep_resp.json() if rep_resp.status_code == 200 else []
            report_listed = any(str(r.get("reportId")) == result["report_id"] for r in reports)
            ok = delivered.get("status") == "DELIVERED" and report_listed
            detail = (f"study status={delivered.get('status')} · signed report "
                      f"{_short(result['report_id'])} "
                      + (f"present in the hospital reports API ({len(reports)} report(s))"
                         if report_listed else "MISSING from the hospital reports API"))
            if not ok:
                add("wf-delivered", _LABELS[4][1], "fail", detail,
                    "The signed report did not reach the hospital portal.")
            else:
                add("wf-delivered", _LABELS[4][1], "pass", detail,
                    "Delivered back to the hospital — the signed report is in the portal.")
        except Exception as exc:
            add("wf-delivered", _LABELS[4][1], "fail",
                _redact(f"{type(exc).__name__}: {exc}", secrets),
                "The hospital-side delivery check failed.")

    # ---- 6. hospital downloads the PDF --------------------------------------
    if blocked or not result["report_id"]:
        skip("wf-pdf", _LABELS[5][1])
    else:
        pdf_check, pdf_path = _pdf_check(hospital, result["report_id"], out_dir, secrets)
        checks.append(pdf_check)
        result["pdf_path"] = pdf_path

    for api in (hospital, clinical):
        try:
            api.close()
        except Exception:
            pass

    result["seconds"] = round(time.monotonic() - started, 2)
    return checks, result


def run_workflow(
    api_base: str,
    study_id: str,
    hospital_id: str,
    radiologist_creds,
    hospital_creds,
    out_dir,
    admin_creds=None,
) -> list[dict]:
    """Console-style entry point: return the six stage-3 checks.

    The resolved ``{study_id, report_id, pdf_path}`` is left in the module-level
    ``LAST_RESULT`` (and returned by :func:`run_workflow_detailed`).
    """
    checks, _ = run_workflow_detailed(
        api_base, study_id, hospital_id, radiologist_creds, hospital_creds,
        out_dir, admin_creds=admin_creds)
    return checks


# ------------------------------------------------------------------ standalone
def _load_env_file(path: str | None = None) -> None:
    """Load KEY=VALUE lines without shell-evaluating them; real env wins."""
    import os
    path = path or os.environ.get("TELERAD_ACCEPTANCE_ENV",
                                  "/home/hermes/.telerad-acceptance.env")
    p = Path(path)
    if not p.is_file():
        return
    for raw in p.read_text().splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        key = key.strip()
        value = value.strip().strip('"').strip("'")
        if key and key not in os.environ:
            os.environ[key] = value


def _pick_eligible(api_base: str, hospital_id: str, creds) -> dict:
    """Smallest READY, unassigned, report-free study (lowest instanceCount)."""
    login = _login(api_base, creds)
    with httpx.Client(timeout=DEFAULT_TIMEOUT) as client:
        resp = client.get(f"{api_base.rstrip('/')}/api/hospitals/{hospital_id}/studies",
                          headers={"Authorization": f"Bearer {login['accessToken']}"})
        resp.raise_for_status()
        rows = resp.json()
    eligible = [s for s in rows
                if s.get("status") == "READY"
                and not s.get("assignedTo")
                and not s.get("hasSignedReport")
                and (s.get("instanceCount") or 0) > 0]
    eligible.sort(key=lambda s: (s.get("instanceCount") or 0, str(s.get("id"))))
    if not eligible:
        raise SystemExit("no eligible study (READY, unassigned, no report) found")
    return eligible[0]


def main(argv: list[str] | None = None) -> int:
    import argparse
    import os

    _load_env_file()
    ap = argparse.ArgumentParser(description="Run the P2 clinical workflow check once")
    ap.add_argument("--api-base", default=os.environ.get("TELERAD_API", "http://127.0.0.1:18080"))
    ap.add_argument("--hospital-id", default=os.environ.get("TELERAD_HOSPITAL_ID", ""))
    ap.add_argument("--study-uid", default=None,
                    help="StudyInstanceUID (default: smallest READY, unassigned study)")
    ap.add_argument("--out", default=str(Path(os.environ.get("FIXTURES_DIR",
                                                            "/home/hermes/dicom-fixtures")) / "reports"))
    args = ap.parse_args(argv)

    rad_creds = {"email": os.environ.get("TELERAD_RADIOLOGIST_EMAIL", "rad@telerad.local"),
                 "password": os.environ.get("TELERAD_RADIOLOGIST_PASSWORD", "password")}
    hosp_creds = {"email": os.environ.get("TELERAD_HOSPITAL_USER_EMAIL", "staff@demohosp.local"),
                  "password": os.environ.get("TELERAD_HOSPITAL_USER_PASSWORD", "password")}
    admin_creds = {"email": os.environ.get("TELERAD_ADMIN_EMAIL", "admin@telerad.local"),
                   "password": os.environ.get("TELERAD_ADMIN_PASSWORD", "password")}

    uid = args.study_uid
    if not uid:
        chosen = _pick_eligible(args.api_base, args.hospital_id, hosp_creds)
        uid = chosen.get("studyInstanceUid")
        print(f"chosen study : {chosen.get('id')}  n={chosen.get('instanceCount')}  "
              f"status={chosen.get('status')}  {chosen.get('studyDescription')!r}")
        print(f"study UID    : {uid}")

    checks, result = run_workflow_detailed(
        args.api_base, uid, args.hospital_id, rad_creds, hosp_creds, args.out,
        admin_creds=admin_creds)
    print(json.dumps(checks, indent=2))
    print("result:", json.dumps(result, indent=2))
    failed = [c for c in checks if c["status"] == "fail"]
    if not checks:
        print("RESULT: no study resolved — stage 2 already reported the miss.")
        return 0
    print("RESULT:", "all six checks passed" if not failed
          else f"{len(failed)} check(s) FAILED")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
