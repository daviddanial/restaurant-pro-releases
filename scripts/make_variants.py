#!/usr/bin/env python3
"""
Generate the Tier-1 acceptance variant set: ~24 small studies, one command.

Why variants, not datasets
--------------------------
Most of the test-study library can be derived from one base study by editing tags,
re-encoding the transfer syntax, or corrupting bytes. Each variant here is *small*
(a handful of instances) so a full sweep takes seconds, and each carries an explicit
**expectation** in its manifest, because for negative studies "rejected cleanly" is
the PASS condition — the console cannot score them without being told what to expect.

Every variant gets fresh Study/Series/SOP UIDs, so any of them can be sent
independently and repeatedly without colliding with another.

Transfer syntaxes use the GDCM/DCMTK converters, which are encoders; the Python
plugins in this image are decode-only. JPEG 2000 is deliberately absent: the only
available encoder (`gdcmconv --jpeg2000`) silently fell back to uncompressed here,
and shipping a file named "jpeg2000" that is actually uncompressed would be a lie
encoded in a test fixture.

Usage
-----
  ./make_variants.py                       # everything
  ./make_variants.py --only syntax,meta    # one or more groups
  ./make_variants.py --list                # show what would be built
"""
from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

try:
    import pydicom
    from pydicom.dataset import FileMetaDataset
    from pydicom.uid import generate_uid, ExplicitVRLittleEndian
except ImportError:
    sys.exit("pydicom is required")

FIXTURES = Path("/home/hermes/dicom-fixtures")
BASE = FIXTURES / "S" / "s-24.zip"          # 24 instances, 5 series, de-identified
OUT = FIXTURES / "V"
PROVENANCE = ("derived from verified fixture S (already de-identified); fresh UIDs, "
              "generated by scripts/make_variants.py")

CR_STORAGE = "1.2.840.10008.5.1.4.1.1.1"
DX_PRESENTATION = "1.2.840.10008.5.1.4.1.1.1.1"
MR_STORAGE = "1.2.840.10008.5.1.4.1.1.4"


# --------------------------------------------------------------------------- helpers
def load_base(tmp: Path) -> list[Path]:
    with zipfile.ZipFile(BASE) as z:
        z.extractall(tmp / "base")
    return sorted((tmp / "base").rglob("*.dcm"))


def study_uids() -> tuple[str, str]:
    return generate_uid(), generate_uid()   # study, frame-of-reference


def rewrite(ds, study_uid: str, frame_uid: str, series_index: int,
            modality: str | None = None, sop_class: str | None = None,
            new_series: bool = False) -> None:
    """Give an instance fresh identity. Modality/SOP class surgery is optional."""
    ds.StudyInstanceUID = study_uid
    ds.FrameOfReferenceUID = frame_uid
    if new_series:
        ds.SeriesInstanceUID = generate_uid()
    ds.SOPInstanceUID = generate_uid()
    if modality:
        ds.Modality = modality
    if sop_class:
        ds.SOPClassUID = sop_class
    if ds.file_meta is None:
        ds.file_meta = FileMetaDataset()
    ds.file_meta.MediaStorageSOPInstanceUID = ds.SOPInstanceUID
    ds.file_meta.MediaStorageSOPClassUID = ds.SOPClassUID
    if not getattr(ds.file_meta, "TransferSyntaxUID", None):
        ds.file_meta.TransferSyntaxUID = ExplicitVRLittleEndian
    ds.SeriesNumber = series_index


def write_zip(files: list[Path], dest: Path) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(dest, "w", zipfile.ZIP_DEFLATED) as z:
        for f in files:
            z.write(f, f.name)


def emit(name: str, group: str, expectation: dict, files: list[Path],
         extra_note: str = "", study_uid: str | None = None) -> dict:
    dest = OUT / name / f"{name}.zip"
    write_zip(files, dest)
    manifest = {
        "synthetic": True,
        "provenance": PROVENANCE,
        "group": group,
        "expected": expectation,
        # The console verifies by UID, so every variant records the study it should create
        # (a sentinel for the variants that contain no valid DICOM at all).
        "study_instance_uid": study_uid or generate_uid(),
    }
    (OUT / name / "manifest.json").write_text(json.dumps(manifest, indent=2))
    n = len(files)
    print(f"  {name:<24} {group:<9} {n:>3} inst  expect={expectation['outcome']}"
          + (f"  {extra_note}" if extra_note else ""))
    return manifest


def convert(src: Path, dest: Path, tool: str, args: list[str]) -> bool:
    r = subprocess.run([tool, *args, str(src), str(dest)],
                       capture_output=True, text=True)
    return r.returncode == 0 and dest.exists()


# --------------------------------------------------------------------------- groups
def g_base(tmp: Path, files: list[Path]) -> None:
    print("\n[baseline / scale]")
    for name, take, note in (
        ("single-image", 1, "smallest valid study"),
        ("small-ct-head", 12, "fast smoke test"),
        ("single-image-series", 3, "one series, one image"),
    ):
        study, frame = study_uids()
        outdir = tmp / name
        outdir.mkdir(parents=True, exist_ok=True)
        kept = []
        for i, f in enumerate(files[:take]):
            ds = pydicom.dcmread(str(f))
            rewrite(ds, study, frame, 1, new_series=(i == 0))
            p = outdir / f.name
            ds.save_as(str(p))
            kept.append(p)
        emit(name, "baseline", {
            "outcome": "ingest_full", "instances": take, "series": 1,
            "plain": f"All {take} instance(s) ingest; study becomes READY."}, kept, note, study)


def g_modality(tmp: Path, files: list[Path]) -> None:
    print("\n[modality variety]  (tags changed on CT pixel data — ingest/routing is real,"
          " the anatomy is not)")
    for name, mod, sop, take in (("cr-synthetic", "CR", CR_STORAGE, 2),
                                 ("dx-synthetic", "DX", DX_PRESENTATION, 2),
                                 ("mr-synthetic", "MR", MR_STORAGE, 3)):
        study, frame = study_uids()
        outdir = tmp / name
        outdir.mkdir(parents=True, exist_ok=True)
        kept = []
        for i, f in enumerate(files[:take]):
            ds = pydicom.dcmread(str(f))
            rewrite(ds, study, frame, 1, modality=mod, sop_class=sop, new_series=(i == 0))
            p = outdir / f.name
            ds.save_as(str(p))
            kept.append(p)
        emit(name, "modality", {
            "outcome": "ingest_full", "instances": take, "series": 1, "modality": mod,
            "plain": f"A {mod} study ingests and is assigned to the sending hospital."},
            kept, f"modality={mod}", study)


def g_syntax(tmp: Path, files: list[Path]) -> None:
    print("\n[transfer syntaxes]")
    # (name, tool, args, resulting UID for verification)
    jobs = [
        ("ts-implicit", None, None, "1.2.840.10008.1.2"),
        ("ts-deflated", None, None, "1.2.840.10008.1.2.1.99"),
        ("ts-rle", "dcmcrle", [], "1.2.840.10008.1.2.5"),
        ("ts-jpeg-baseline", "dcmcjpeg", ["+eb"], "1.2.840.10008.1.2.4.50"),
        ("ts-jpeg-lossless", "dcmcjpeg", ["+el"], "1.2.840.10008.1.2.4.57"),
        ("ts-jpegls", "dcmcjpls", [], "1.2.840.10008.1.2.4.80"),
    ]
    for name, tool, args, ts in jobs:
        study, frame = study_uids()
        outdir = tmp / name
        outdir.mkdir(parents=True, exist_ok=True)
        kept = []
        for i, f in enumerate(files[:2]):
            ds = pydicom.dcmread(str(f))
            rewrite(ds, study, frame, 1, new_series=(i == 0))
            if name == "ts-implicit":
                ds.file_meta.TransferSyntaxUID = "1.2.840.10008.1.2"
            elif name == "ts-deflated":
                ds.file_meta.TransferSyntaxUID = "1.2.840.10008.1.2.1.99"
            p = outdir / f.name
            ds.save_as(str(p))
            if tool:
                conv = outdir / f"c_{f.name}"
                if not convert(p, conv, tool, args or []):
                    print(f"  {name}: converter {tool} FAILED — skipped")
                    kept = []
                    break
                p.unlink()
                conv.rename(p)
            kept.append(p)
        if not kept:
            continue
        emit(name, "syntax", {
            "outcome": "ingest_full", "instances": len(kept), "series": 1,
            "transfer_syntax": ts,
            "plain": f"A study encoded as {ts} is accepted; the viewer must render it."},
            kept, f"ts={ts}", study)


def g_meta(tmp: Path, files: list[Path]) -> None:
    print("\n[metadata edge cases]")
    edits = [
        ("meta-no-patientid", "no-study-member", lambda ds: setattr(ds, "PatientID", ""),
         "ingest_flagged", "empty PatientID must be stored/flagged, never silently lost"),
        ("meta-amharic", "no-study-member",
         lambda ds: (setattr(ds, "PatientName", "ዮሴፍ^ተስፋዬ"), setattr(ds, "SpecificCharacterSet", "ISO_IR 192")),
         "ingest_full", "Amharic (Ge'ez) name must round-trip without garbling"),
        ("meta-long-names", "no-study-member",
         lambda ds: (setattr(ds, "PatientName", "A" * 60 + "^" + "B" * 20),
                     setattr(ds, "StudyDescription", "L" * 64)),
         "ingest_full", "very long names/descriptions must not break ingest"),
        ("meta-empty-desc", "no-study-member",
         lambda ds: (setattr(ds, "StudyDescription", ""), setattr(ds, "Modality", "")),
         "ingest_full", "empty description/modality must still ingest"),
        ("meta-future-dob", "no-study-member",
         lambda ds: setattr(ds, "PatientBirthDate", "20301231"),
         "ingest_full", "an implausible birth date must not crash ingest"),
        ("meta-sex-o", "no-study-member",
         lambda ds: setattr(ds, "PatientSex", "O"),
         "ingest_full", "sex coded 'O' must ingest"),
    ]
    for name, _ignore, fn, outcome, plain in edits:
        study, frame = study_uids()
        outdir = tmp / name
        outdir.mkdir(parents=True, exist_ok=True)
        kept = []
        for i, f in enumerate(files[:2]):
            ds = pydicom.dcmread(str(f))
            rewrite(ds, study, frame, 1, new_series=(i == 0))
            fn(ds)
            p = outdir / f.name
            ds.save_as(str(p))
            kept.append(p)
        emit(name, "meta", {"outcome": outcome, "instances": 2, "series": 1,
                            "plain": plain}, kept, study_uid=study)


def g_bad(tmp: Path, files: list[Path]) -> None:
    print("\n[corrupt / malformed]")
    # 1. zero-byte object
    study, frame = study_uids()
    d = tmp / "bad-zero-byte"; d.mkdir(parents=True, exist_ok=True)
    (d / "zero.dcm").write_bytes(b"")
    emit("bad-zero-byte", "corrupt", {
        "outcome": "no_study", "instances": 1, "series": 0,
        "plain": "A zero-byte object has nothing to store: no study should be created."},
        [d / "zero.dcm"], study_uid=study)

    # 2. non-DICOM payload with a .dcm name
    d = tmp / "bad-non-dicom"; d.mkdir(parents=True, exist_ok=True)
    (d / "notdicom.dcm").write_text("this is not a DICOM object\n" * 20)
    emit("bad-non-dicom", "corrupt", {
        "outcome": "no_study", "instances": 1, "series": 0,
        "plain": "A non-DICOM payload must be refused, not stored as a study."},
        [d / "notdicom.dcm"], study_uid=study)

    # 3. truncated object
    study, frame = study_uids()
    d = tmp / "bad-truncated"; d.mkdir(parents=True, exist_ok=True)
    ds = pydicom.dcmread(str(files[0]))
    rewrite(ds, study, frame, 1, new_series=True)
    full = d / "full.dcm"; ds.save_as(str(full))
    raw = full.read_bytes()
    trunc = d / "truncated.dcm"; trunc.write_bytes(raw[:len(raw) // 2]); full.unlink()
    emit("bad-truncated", "corrupt", {
        "outcome": "either", "instances": 1, "series": 0,
        "plain": ("A truncated object must produce a clear error. Storing the bytes but "
                  "failing to render is acceptable ONLY if the platform says so — the "
                  "console reports which happened.")}, [trunc], study_uid=study)

    # 4. one corrupt among good ones
    study, frame = study_uids()
    d = tmp / "bad-one-of-six"; d.mkdir(parents=True, exist_ok=True)
    kept = []
    for i, f in enumerate(files[:5]):
        ds = pydicom.dcmread(str(f))
        rewrite(ds, study, frame, 1, new_series=(i == 0))
        p = d / f.name; ds.save_as(str(p)); kept.append(p)
    (d / "zzz-corrupt.dcm").write_bytes(b"\x00" * 4096)
    kept.append(d / "zzz-corrupt.dcm")
    emit("bad-one-of-six", "corrupt", {
        "outcome": "partial_ingest", "instances": 6, "expected_stored": 5,
        "plain": "The 5 good images must be stored; the corrupt one reported, not fatal."},
        kept, study_uid=study)


GROUPS = {"baseline": g_base, "modality": g_modality, "syntax": g_syntax,
          "meta": g_meta, "corrupt": g_bad}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--only", default=",".join(GROUPS),
                    help=f"comma-separated groups from: {', '.join(GROUPS)}")
    ap.add_argument("--list", action="store_true")
    args = ap.parse_args()
    if args.list:
        print("groups:", ", ".join(GROUPS)); return 0
    if not BASE.exists():
        sys.exit(f"base fixture not found: {BASE}")

    wanted = [g.strip() for g in args.only.split(",") if g.strip()]
    unknown = [g for g in wanted if g not in GROUPS]
    if unknown:
        sys.exit(f"unknown group(s): {unknown}")

    tmp = Path(tempfile.mkdtemp(prefix="variants-"))
    try:
        files = load_base(tmp)
        print(f"base: {BASE.name} ({len(files)} instances)")
        for g in wanted:
            GROUPS[g](tmp, files)
        print(f"\nvariant fixtures written under {OUT}")
        total = len(list(OUT.glob("*/manifest.json")))
        print(f"registered fixtures: {total}")
        print("\nNOTE: the console scores each fixture by its recorded expectation, so a")
        print("clean rejection counts as a PASS for the negative studies.")
        return 0
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


if __name__ == "__main__":
    raise SystemExit(main())
