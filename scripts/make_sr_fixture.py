#!/usr/bin/env python3
"""Derive a small de-identified study that carries unsupported SR objects (P3).

Why this exists
---------------
TeleRad's SCP advertises a fixed list of storage SOP classes
(`DicomScpServer.commonStorageSopClasses()`) and that list contains **no** SR
class. A C-STORE for an SR object therefore never negotiates a presentation
context: pynetdicom raises, the simulator records ``no-accepted-context``, and
the CT images in the same study store normally. That is finding **F1** — the
platform silently drops dose / enhanced SR objects rather than refusing the
whole study.

The P3 negative suite needs a *small* fixture that reproduces that split without
consuming a fresh positive fixture. This generator derives one from an existing
already-de-identified full fixture (`F/f-full.zip`, which carries three X-Ray
Radiation Dose SR and three Enhanced SR objects). It keeps the original SOP
Class UIDs — that is the whole point — but assigns the derived study fresh
Study/Series/SOP UIDs so it can be sent on its own without colliding with the
spent source study.

Output root is a parameter so the generator can write anywhere:
  * host-side, into the standard fixture tree (Hermes runs this):
        /opt/dicom-tools/bin/python scripts/make_sr_fixture.py \\
            --out-root /home/hermes/dicom-fixtures
  * a sandboxed agent, into a repo-local directory:
        /opt/dicom-tools/bin/python scripts/make_sr_fixture.py \\
            --out-root scripts/acceptance-console/negative-fixtures

Layout matches `make_variants.py`: ``<out-root>/<name>/<name>.zip`` plus a
``manifest.json`` whose ``expected`` block tells the console what "correct"
means (partial ingest: the CT objects store, the SR objects are declined).

The source material is already de-identified (fixture F) and the derived study
is marked synthetic in its manifest, so it is selectable by the console without
a new de-identification gate.
"""
from __future__ import annotations

import argparse
import json
import sys
import tempfile
import zipfile
from pathlib import Path

try:
    import pydicom
except ImportError:  # pragma: no cover
    sys.exit("pydicom is required")

HERE = Path(__file__).resolve().parent
DEFAULT_BASE = Path("/home/hermes/dicom-fixtures/F/f-full.zip")
DEFAULT_OUT_ROOT = Path("/home/hermes/dicom-fixtures")
DEFAULT_NAME = "sr-unsupported"

CT_IMAGE_STORAGE = "1.2.840.10008.5.1.4.1.1.2"
SR_SOP_CLASSES = {
    "1.2.840.10008.5.1.4.1.1.88.22": "Enhanced SR",
    "1.2.840.10008.5.1.4.1.1.88.67": "X-Ray Radiation Dose SR",
    # A couple more SR flavours are recognised if a future base carries them.
    "1.2.840.10008.5.1.4.1.1.88.33": "Comprehensive SR",
    "1.2.840.10008.5.1.4.1.1.88.11": "Basic Text SR",
}
PROVENANCE = ("derived from verified fixture F (already de-identified); fresh UIDs, "
              "SOP classes preserved, generated by scripts/make_sr_fixture.py")


def _candidate_paths(base: Path) -> list[tuple[str, str, str]]:
    """Return ``[(zip_name, sop_class_uid, series_instance_uid)]`` for every object."""
    out: list[tuple[str, str, str]] = []
    with zipfile.ZipFile(base) as zf:
        for name in zf.namelist():
            if not name.lower().endswith(".dcm"):
                continue
            try:
                ds = pydicom.dcmread(zf.open(name), stop_before_pixels=True, force=True)
            except Exception:
                continue
            out.append((name, str(ds.get("SOPClassUID", "")),
                        str(ds.get("SeriesInstanceUID", ""))))
    return out


def _pick(base: Path, ct_count: int, sr_count: int) -> tuple[list[str], list[str], list[str]]:
    """Choose CT instances plus one SR instance per distinct SR SOP class."""
    candidates = _candidate_paths(base)
    ct = [n for n, sop, _ in candidates if sop == CT_IMAGE_STORAGE][:ct_count]
    sr: list[str] = []
    seen_classes: set[str] = set()
    for name, sop, _ in candidates:
        if sop in SR_SOP_CLASSES and sop not in seen_classes:
            sr.append(name)
            seen_classes.add(sop)
            if len(sr) >= sr_count:
                break
    # Any remaining SR objects (if fewer distinct classes than requested).
    for name, sop, _ in candidates:
        if len(sr) >= sr_count:
            break
        if sop in SR_SOP_CLASSES and name not in sr:
            sr.append(name)
    if not ct:
        raise SystemExit(f"no CT Image Storage instances found in {base}")
    if not sr:
        raise SystemExit(f"no SR instances found in {base}")
    return ct, sr, [sop for _, sop, _ in candidates if sop in SR_SOP_CLASSES]


def _rewrite(ds, study_uid: str, frame_uid: str, series_uid: str, series_number: int):
    """Fresh identity, same SOP class. Media storage UIDs follow."""
    ds.StudyInstanceUID = study_uid
    ds.FrameOfReferenceUID = frame_uid
    ds.SeriesInstanceUID = series_uid
    ds.SeriesNumber = series_number
    ds.SOPInstanceUID = pydicom.uid.generate_uid()
    if ds.file_meta is None:
        ds.file_meta = pydicom.dataset.FileMetaDataset()
    ds.file_meta.MediaStorageSOPInstanceUID = ds.SOPInstanceUID
    ds.file_meta.MediaStorageSOPClassUID = ds.SOPClassUID
    if not getattr(ds.file_meta, "TransferSyntaxUID", None):
        ds.file_meta.TransferSyntaxUID = pydicom.uid.ExplicitVRLittleEndian


def build(base: Path, out_root: Path, name: str, ct_count: int, sr_count: int) -> dict:
    if not base.is_file():
        raise SystemExit(f"base fixture not found: {base}")
    ct_names, sr_names, all_sr = _pick(base, ct_count, sr_count)
    study_uid = pydicom.uid.generate_uid()
    frame_uid = pydicom.uid.generate_uid()

    out_dir = out_root / name
    out_dir.mkdir(parents=True, exist_ok=True)
    tmp = Path(tempfile.mkdtemp(prefix="sr-fixture-"))

    written: list[Path] = []
    ct_series = pydicom.uid.generate_uid()
    with zipfile.ZipFile(base) as zf:
        for i, zname in enumerate(ct_names):
            ds = pydicom.dcmread(zf.open(zname), force=True)
            _rewrite(ds, study_uid, frame_uid, ct_series, 1)
            p = tmp / f"ct-{i + 1:02d}.dcm"
            ds.save_as(str(p))
            written.append(p)
        for i, zname in enumerate(sr_names):
            ds = pydicom.dcmread(zf.open(zname), force=True)
            sop = str(ds.get("SOPClassUID", ""))
            # Each SR object gets its own series; a series whose every instance is
            # declined never becomes a row in TeleRad, so this mirrors the real
            # F1 behaviour (an SR-only series disappears entirely).
            _rewrite(ds, study_uid, frame_uid, pydicom.uid.generate_uid(), 10 + i)
            label = SR_SOP_CLASSES.get(sop, "SR").replace(" ", "-").lower()
            p = tmp / f"sr-{i + 1:02d}-{label}.dcm"
            ds.save_as(str(p))
            written.append(p)

    dest = out_dir / f"{name}.zip"
    with zipfile.ZipFile(dest, "w", zipfile.ZIP_DEFLATED) as z:
        for f in written:
            z.write(f, f.name)
    for f in written:
        f.unlink()
    tmp.rmdir()

    expectation = {
        "outcome": "partial_ingest",
        "instances": len(written),
        "expected_stored": len(ct_names),
        "series": 1 + len(sr_names),
        "modality": "CT",
        "plain": (f"The {len(ct_names)} CT image(s) are stored and the study is usable; the "
                  f"{len(sr_names)} SR object(s) are declined because TeleRad's SCP negotiates "
                  f"no presentation context for SR (finding F1)."),
    }
    manifest = {
        "synthetic": True,
        "provenance": PROVENANCE,
        "group": "negative-sr",
        "expected": expectation,
        "study_instance_uid": study_uid,
        "sr_sop_classes": {sop: SR_SOP_CLASSES[sop] for sop in sorted(set(all_sr))},
    }
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2))
    return {"zip": str(dest), "manifest": str(out_dir / "manifest.json"),
            "study_instance_uid": study_uid, "ct": len(ct_names), "sr": len(sr_names),
            "expected_stored": len(ct_names)}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out-root", type=Path, default=DEFAULT_OUT_ROOT,
                    help=f"root under which <name>/ is written (default: {DEFAULT_OUT_ROOT})")
    ap.add_argument("--base", type=Path, default=DEFAULT_BASE,
                    help=f"de-identified source archive carrying SR objects (default: {DEFAULT_BASE})")
    ap.add_argument("--name", default=DEFAULT_NAME)
    ap.add_argument("--ct", type=int, default=3, help="CT instances to include (default 3)")
    ap.add_argument("--sr", type=int, default=2, help="SR instances to include (default 2)")
    args = ap.parse_args(argv)

    result = build(args.base.expanduser(), args.out_root.expanduser(), args.name,
                   args.ct, args.sr)
    print(json.dumps(result, indent=2))
    print(f"\nfixture written: {result['zip']}")
    print(f"  study UID : {result['study_instance_uid']}")
    print(f"  contents  : {result['ct']} CT stored + {result['sr']} SR declined (expected)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
