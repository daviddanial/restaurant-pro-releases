-- Central imaging procedure list (KB note 15 §9), seeded once; admins maintain it in Admin → Procedures.
-- Merged from three OpenMRS concept dictionaries and the ultrasound report templates:
-- sides merged (the side is chosen on the order), typos fixed, modality corrected.

CREATE TABLE procedures (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    modality    VARCHAR(16)  NOT NULL,
    name        VARCHAR(255) NOT NULL,
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    sort_order  INT          NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX ux_procedures_modality_name ON procedures (modality, lower(name));

-- The procedure an order was made for (the name is also copied to procedure_description).
ALTER TABLE imaging_orders ADD COLUMN procedure_id UUID REFERENCES procedures(id);

